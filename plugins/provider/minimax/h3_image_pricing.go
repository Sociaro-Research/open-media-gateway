func h3PriceCells(line string) []string {
	line = strings.TrimSpace(line)
	if !strings.HasPrefix(line, "|") || !strings.HasSuffix(line, "|") {
		return nil
	}
	cells := strings.Split(strings.Trim(line, "|"), "|")
	for i, s := range cells {
		cells[i] = strings.Join(strings.Fields(strings.NewReplacer("**", "", `\$`, "$").Replace(s)), " ")
	}
	return cells
}

// Parse just the standard list-price table. An incomplete refresh returns the
// previously verified map intact, including its timestamp.
func h3ImageTariffs(previous map[string]core.PricingSnapshot, document string, checked time.Time) (map[string]core.PricingSnapshot, error) {
	unknown := errors.New("MiniMax H3 image tariff or prompt enhancement terms could not be verified")
	if len(document) > 2<<20 || checked.IsZero() {
		return previous, unknown
	}
	_, section, found := strings.Cut("\n"+document, "\n## Image\n")
	if !found || strings.Count("\n"+document, "\n## Image\n") != 1 {
		return previous, unknown
	}
	section, _, _ = strings.Cut(section, "\n## ")
	if !strings.Contains(section, "Text input tokens include those generated by prompt enhancement.") || strings.Count(section, "\n### Image Generation\n") != 1 {
		return previous, unknown
	}
	_, table, _ := strings.Cut(section, "\n### Image Generation\n")
	table, _, _ = strings.Cut(table, "\n### ")
	lines := strings.Split(strings.TrimSpace(table), "\n")
	header := []string{"Model", "Input Text $ / M tokens", "Input Image $ / M tokens", "Output Image $ / M tokens"}
	if len(lines) != 4 || !slices.Equal(h3PriceCells(lines[0]), header) || !slices.Equal(h3PriceCells(lines[1]), []string{":-", ":-:", ":-:", ":-:"}) {
		return previous, unknown
	}
	result := map[string]core.PricingSnapshot{}
	for _, line := range lines[2:] {
		cells := h3PriceCells(line)
		if len(cells) != 4 {
			return previous, unknown
		}
		var id string
		switch cells[0] {
		case h3Image + " Standard":
			id = h3Image
		case h3ImageHighspeed + " Highspeed":
			id = h3ImageHighspeed
		default:
			return previous, unknown
		}
		if _, exists := result[id]; exists {
			return previous, unknown
		}
		snapshot := core.PricingSnapshot{Currency: "USD", Region: "Global", Unit: "token", Per: 1000000, Source: priceSource, CheckedAt: checked.UTC(), Version: checked.UTC().Format("2006-01-02"), EstimateDescription: "Token quantities depend on provider-reported usage, including built-in prompt enhancement."}
		for i, name := range []string{"text_input_tokens", "image_input_tokens", "image_output_tokens"} {
			match := dollarAmount.FindStringSubmatch(cells[i+1])
			if match == nil {
				return previous, unknown
			}
			price, e := money.Parse(match[1])
			if e != nil || price <= 0 {
				return previous, unknown
			}
			snapshot.Components = append(snapshot.Components, core.PricingComponent{Metric: name, Price: price, Per: 1000000})
		}
		result[id] = snapshot
	}
	return result, nil
}

func (a *h3Images) Quote(ctx context.Context, _ core.MediaModel, r core.MediaRequest) (core.TaskCost, string, error) {
	if err := a.ValidateRequest(ctx, r); err != nil {
		return core.TaskCost{}, "", err
	}
	rate, ok := a.tariffs[r.Model]
	if !ok {
		return core.TaskCost{}, "", core.ErrPricingUnavailable
	}
	return core.TaskCost{QuantityUnknown: true, Status: "quantity_unknown", Pricing: rate, QuotedAt: time.Now().UTC()}, "", nil
}
